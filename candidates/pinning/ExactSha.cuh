#define QSB_SHA_STATE_WORDS 13
static inline uint32_t qsb_host_ror(uint32_t x, unsigned n) {
    return (x >> n) | (x << (32 - n));
}
static inline uint32_t qsb_host_S0(uint32_t x) {
    return qsb_host_ror(x,2) ^ qsb_host_ror(x,13) ^ qsb_host_ror(x,22);
}
static inline uint32_t qsb_host_S1(uint32_t x) {
    return qsb_host_ror(x,6) ^ qsb_host_ror(x,11) ^ qsb_host_ror(x,25);
}
/* p[0..7] is the original feed-forward state. Five scalar constants are
 * derived once per sequence, then copied in each slot's own async stream. */
static inline void qsb_sha_tail_precompute(uint32_t p[QSB_SHA_STATE_WORDS], uint32_t w2) {
    uint32_t v = p[7] + qsb_host_S1(p[4]) + (p[6] ^ (p[4] & (p[5] ^ p[6]))) + 0x428a2f98u;
    p[8] = v + qsb_host_S0(p[0]) + ((p[0] & p[1]) | (p[2] & (p[0] | p[1])));
    p[9] = v + p[3];
    p[10] = p[6] + 0x71374491u;
    p[11] = p[5] + 0xb5c0fbcfu + w2;
    p[12] = p[4] + 0xe9b5dba5u;
}
