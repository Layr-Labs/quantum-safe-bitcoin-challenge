// Exact signed-middle Karatsuba with fused sign correction and full carry chains.
// Exact 512-bit signed-middle product followed by the promoted C31 raw fold.
#pragma once
static_assert(QSB_C31 && QSB_SHORT_CARRY,
              "Mul48 preserves the selected promoted C31 short-carry fold");
__device__ __forceinline__ void qsb_predicated_raw_mul48(
    uint64_t *out,const uint64_t *a,const uint64_t *b) {
    uint64_t r0,r1,r2,r3;
    asm(
        "{\n"
        ".reg .u32 kp_d4,kp_c4,kp_ma32,kp_mb32;\n"
        ".reg .pred kp_pa,kp_pb;\n"
        ".reg .u32 kp_a0,kp_a1,kp_a2,kp_a3,kp_b0,kp_b1,kp_b2,kp_b3,kp_cy,kp_oddcy,kp_o7;\n"
        ".reg .u32 kp_x0,kp_x1,kp_x2,kp_x3,kp_x4,kp_x5,kp_x6,kp_x7,kp_y1,kp_y2,kp_y3,kp_y4,kp_y5,kp_y6;\n"
        ".reg .u64 kp_e0,kp_e1,kp_e2,kp_e3,kp_o0,kp_o1,kp_o2,kp_t,kp_odd_t,kp_odd_lc;\n"
        ".reg .u64 kp_al,kp_ah,kp_ah0,kp_ah1,kp_bl,kp_bh,kp_bh0,kp_bh1,kp_da0,kp_da1,kp_db0,kp_db1;\n"
        ".reg .u64 kp_p0,kp_p1,kp_p2,kp_p3,kp_p4,kp_p5,kp_p6,kp_p7,kp_l0,kp_l1,kp_l2,kp_l3,kp_h0,kp_h1,kp_h2,kp_h3,kp_d0,kp_d1,kp_d2,kp_d3,kp_c0,kp_c1;\n"
        "mov.b64 kp_al,%4;mov.b64 kp_ah,%5;mov.b64 kp_ah0,%6;mov.b64 kp_ah1,%7;\n"
        "mov.b64 kp_bl,%8;mov.b64 kp_bh,%9;mov.b64 kp_bh0,%10;mov.b64 kp_bh1,%11;\n"
        "sub.cc.u64 kp_da0,kp_al,kp_ah0;subc.cc.u64 kp_da1,kp_ah,kp_ah1;subc.u32 kp_ma32,0,0;setp.ne.u32 kp_pa,kp_ma32,0;\n"
        "sub.cc.u64 kp_db0,kp_bl,kp_bh0;subc.cc.u64 kp_db1,kp_bh,kp_bh1;subc.u32 kp_mb32,0,0;setp.ne.u32 kp_pb,kp_mb32,0;\n"
        "mov.b64 {kp_a0,kp_a1},kp_da0;mov.b64 {kp_a2,kp_a3},kp_da1;\n"
        "mov.b64 {kp_b0,kp_b1},kp_db0;mov.b64 {kp_b2,kp_b3},kp_db1;\n"
        "mul.wide.u32 kp_e0,kp_a0,kp_b0;mul.wide.u32 kp_o0,kp_a0,kp_b1;\n"
        "mul.wide.u32 kp_e1,kp_a0,kp_b2;mul.wide.u32 kp_o1,kp_a0,kp_b3;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b1;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b3;addc.u64 kp_e2,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b0;add.cc.u64 kp_o0,kp_o0,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b2;addc.cc.u64 kp_o1,kp_o1,kp_odd_t;addc.u32 kp_oddcy,0,0;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b0;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b2;addc.cc.u64 kp_e2,kp_e2,kp_t;addc.u32 kp_cy,0,0;\n"
        "mov.b64 kp_odd_lc,{kp_oddcy,kp_cy};\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b1;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b3;addc.u64 kp_o2,kp_odd_t,kp_odd_lc;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b1;add.cc.u64 kp_e2,kp_e2,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b3;addc.u64 kp_e3,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b0;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b2;addc.cc.u64 kp_o2,kp_o2,kp_odd_t;addc.u32 kp_o7,0,0;\n"
        "mov.b64 {kp_x0,kp_x1},kp_e0;mov.b64 {kp_x2,kp_x3},kp_e1;\n"
        "mov.b64 {kp_x4,kp_x5},kp_e2;mov.b64 {kp_x6,kp_x7},kp_e3;\n"
        "mov.b64 {kp_y1,kp_y2},kp_o0;mov.b64 {kp_y3,kp_y4},kp_o1;mov.b64 {kp_y5,kp_y6},kp_o2;\n"
        "add.cc.u32 kp_x1,kp_x1,kp_y1;addc.cc.u32 kp_x2,kp_x2,kp_y2;addc.cc.u32 kp_x3,kp_x3,kp_y3;\n"
        "addc.cc.u32 kp_x4,kp_x4,kp_y4;addc.cc.u32 kp_x5,kp_x5,kp_y5;addc.cc.u32 kp_x6,kp_x6,kp_y6;\n"
        "addc.u32 kp_x7,kp_x7,kp_o7;\n"
        "mov.b64 kp_d0,{kp_x0,kp_x1};\n"
        "mov.b64 kp_d1,{kp_x2,kp_x3};\n"
        "mov.b64 kp_d2,{kp_x4,kp_x5};\n"
        "mov.b64 kp_d3,{kp_x6,kp_x7};\n"
        "mov.u32 kp_d4,0;\n"
        "@kp_pa sub.cc.u64 kp_d2,kp_d2,kp_db0;\n"
        "@kp_pa subc.cc.u64 kp_d3,kp_d3,kp_db1;\n"
        "@kp_pa subc.u32 kp_d4,kp_d4,0;\n"
        "@kp_pb sub.cc.u64 kp_d2,kp_d2,kp_da0;\n"
        "@kp_pb subc.cc.u64 kp_d3,kp_d3,kp_da1;\n"
        "@kp_pb subc.u32 kp_d4,kp_d4,kp_ma32;\n"
        "mov.b64 {kp_a0,kp_a1},kp_al;mov.b64 {kp_a2,kp_a3},kp_ah;\n"
        "mov.b64 {kp_b0,kp_b1},kp_bl;mov.b64 {kp_b2,kp_b3},kp_bh;\n"
        "mul.wide.u32 kp_e0,kp_a0,kp_b0;mul.wide.u32 kp_o0,kp_a0,kp_b1;\n"
        "mul.wide.u32 kp_e1,kp_a0,kp_b2;mul.wide.u32 kp_o1,kp_a0,kp_b3;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b1;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b3;addc.u64 kp_e2,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b0;add.cc.u64 kp_o0,kp_o0,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b2;addc.cc.u64 kp_o1,kp_o1,kp_odd_t;addc.u32 kp_oddcy,0,0;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b0;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b2;addc.cc.u64 kp_e2,kp_e2,kp_t;addc.u32 kp_cy,0,0;\n"
        "mov.b64 kp_odd_lc,{kp_oddcy,kp_cy};\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b1;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b3;addc.u64 kp_o2,kp_odd_t,kp_odd_lc;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b1;add.cc.u64 kp_e2,kp_e2,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b3;addc.u64 kp_e3,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b0;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b2;addc.cc.u64 kp_o2,kp_o2,kp_odd_t;addc.u32 kp_o7,0,0;\n"
        "mov.b64 {kp_x0,kp_x1},kp_e0;mov.b64 {kp_x2,kp_x3},kp_e1;\n"
        "mov.b64 {kp_x4,kp_x5},kp_e2;mov.b64 {kp_x6,kp_x7},kp_e3;\n"
        "mov.b64 {kp_y1,kp_y2},kp_o0;mov.b64 {kp_y3,kp_y4},kp_o1;mov.b64 {kp_y5,kp_y6},kp_o2;\n"
        "add.cc.u32 kp_x1,kp_x1,kp_y1;addc.cc.u32 kp_x2,kp_x2,kp_y2;addc.cc.u32 kp_x3,kp_x3,kp_y3;\n"
        "addc.cc.u32 kp_x4,kp_x4,kp_y4;addc.cc.u32 kp_x5,kp_x5,kp_y5;addc.cc.u32 kp_x6,kp_x6,kp_y6;\n"
        "addc.u32 kp_x7,kp_x7,kp_o7;\n"
        "mov.b64 kp_l0,{kp_x0,kp_x1};\n"
        "mov.b64 kp_l1,{kp_x2,kp_x3};\n"
        "mov.b64 kp_l2,{kp_x4,kp_x5};\n"
        "mov.b64 kp_l3,{kp_x6,kp_x7};\n"
        "mov.b64 {kp_a0,kp_a1},kp_ah0;mov.b64 {kp_a2,kp_a3},kp_ah1;\n"
        "mov.b64 {kp_b0,kp_b1},kp_bh0;mov.b64 {kp_b2,kp_b3},kp_bh1;\n"
        "mul.wide.u32 kp_e0,kp_a0,kp_b0;mul.wide.u32 kp_o0,kp_a0,kp_b1;\n"
        "mul.wide.u32 kp_e1,kp_a0,kp_b2;mul.wide.u32 kp_o1,kp_a0,kp_b3;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b1;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a1,kp_b3;addc.u64 kp_e2,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b0;add.cc.u64 kp_o0,kp_o0,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a1,kp_b2;addc.cc.u64 kp_o1,kp_o1,kp_odd_t;addc.u32 kp_oddcy,0,0;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b0;add.cc.u64 kp_e1,kp_e1,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a2,kp_b2;addc.cc.u64 kp_e2,kp_e2,kp_t;addc.u32 kp_cy,0,0;\n"
        "mov.b64 kp_odd_lc,{kp_oddcy,kp_cy};\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b1;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a2,kp_b3;addc.u64 kp_o2,kp_odd_t,kp_odd_lc;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b1;add.cc.u64 kp_e2,kp_e2,kp_t;\n"
        "mul.wide.u32 kp_t,kp_a3,kp_b3;addc.u64 kp_e3,kp_t,0;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b0;add.cc.u64 kp_o1,kp_o1,kp_odd_t;\n"
        "mul.wide.u32 kp_odd_t,kp_a3,kp_b2;addc.cc.u64 kp_o2,kp_o2,kp_odd_t;addc.u32 kp_o7,0,0;\n"
        "mov.b64 {kp_x0,kp_x1},kp_e0;mov.b64 {kp_x2,kp_x3},kp_e1;\n"
        "mov.b64 {kp_x4,kp_x5},kp_e2;mov.b64 {kp_x6,kp_x7},kp_e3;\n"
        "mov.b64 {kp_y1,kp_y2},kp_o0;mov.b64 {kp_y3,kp_y4},kp_o1;mov.b64 {kp_y5,kp_y6},kp_o2;\n"
        "add.cc.u32 kp_x1,kp_x1,kp_y1;addc.cc.u32 kp_x2,kp_x2,kp_y2;addc.cc.u32 kp_x3,kp_x3,kp_y3;\n"
        "addc.cc.u32 kp_x4,kp_x4,kp_y4;addc.cc.u32 kp_x5,kp_x5,kp_y5;addc.cc.u32 kp_x6,kp_x6,kp_y6;\n"
        "addc.u32 kp_x7,kp_x7,kp_o7;\n"
        "mov.b64 kp_h0,{kp_x0,kp_x1};\n"
        "mov.b64 kp_h1,{kp_x2,kp_x3};\n"
        "mov.b64 kp_h2,{kp_x4,kp_x5};\n"
        "mov.b64 kp_h3,{kp_x6,kp_x7};\n"
        "add.cc.u64 kp_p2,kp_l0,kp_h0;\n"
        "addc.cc.u64 kp_p3,kp_l1,kp_h1;\n"
        "addc.cc.u64 kp_p4,kp_l2,kp_h2;\n"
        "addc.cc.u64 kp_p5,kp_l3,kp_h3;\n"
        "addc.u32 kp_c4,0,0;\n"
        "sub.cc.u64 kp_d0,kp_p2,kp_d0;\n"
        "subc.cc.u64 kp_d1,kp_p3,kp_d1;\n"
        "subc.cc.u64 kp_d2,kp_p4,kp_d2;\n"
        "subc.cc.u64 kp_d3,kp_p5,kp_d3;\n"
        "subc.u32 kp_c4,kp_c4,kp_d4;\n"
        "mov.b64 kp_p0,kp_l0;mov.b64 kp_p1,kp_l1;mov.b64 kp_c0,{kp_c4,0};\n"
        "add.cc.u64 kp_p2,kp_l2,kp_d0;\n"
        "addc.cc.u64 kp_p3,kp_l3,kp_d1;\n"
        "addc.cc.u64 kp_p4,kp_h0,kp_d2;\n"
        "addc.cc.u64 kp_p5,kp_h1,kp_d3;\n"
        "addc.cc.u64 kp_p6,kp_h2,kp_c0;\n"
        "addc.u64 kp_p7,kp_h3,0;\n"
        ".reg .u32 x0,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15;\n"
        ".reg .u64 t;\n"
        "mov.b64 {x0,x1},kp_p0;\n"
        "mov.b64 {x2,x3},kp_p1;\n"
        "mov.b64 {x4,x5},kp_p2;\n"
        "mov.b64 {x6,x7},kp_p3;\n"
        "mov.b64 {x8,x9},kp_p4;\n"
        "mov.b64 {x10,x11},kp_p5;\n"
        "mov.b64 {x12,x13},kp_p6;\n"
        "mov.b64 {x14,x15},kp_p7;\n"
        ".reg .u64 r0,r1,r2,r3,h0,h1,h2,h3,f0,f1,f2,f3,g0,g1,g2,g3;\n"
        "\t.reg .u32 f8,g8,z0,z1,z2,z3,z4,z5,z6,z7,z8,z9,w0,w1,w2,w3,w4,w5,w6,w7,m0,m1,m2;\n"
        "\tmov.b64 r0, {x0,x1}; mov.b64 r1, {x2,x3}; mov.b64 r2, {x4,x5}; mov.b64 r3, {x6,x7};\n"
        "\tmov.b64 h0, {x8,x9}; mov.b64 h1, {x10,x11}; mov.b64 h2, {x12,x13}; mov.b64 h3, {x14,x15};\n"
        "\tmul.wide.u32 t, x8, 977;  add.cc.u64  f0, r0, t;\n"
        "\tmul.wide.u32 t, x10, 977; addc.cc.u64 f1, r1, t;\n"
        "\tmul.wide.u32 t, x12, 977; addc.cc.u64 f2, r2, t;\n"
        "\tmul.wide.u32 t, x14, 977; addc.cc.u64 f3, r3, t;\n"
        "\taddc.u32 f8, 0, 0;\n"
        "\tmul.wide.u32 t, x9, 977;  add.cc.u64  g0, h0, t;\n"
        "\tmul.wide.u32 t, x11, 977; addc.cc.u64 g1, h1, t;\n"
        "\tmul.wide.u32 t, x13, 977; addc.cc.u64 g2, h2, t;\n"
        "\tmul.wide.u32 t, x15, 977; addc.cc.u64 g3, h3, t;\n"
        "\t\n"
        "\tmov.b64 {z0,z1}, f0;\n"
        "\tmov.b64 {z2,z3}, f1;\n"
        "\tmov.b64 {z4,z5}, f2;\n"
        "\tmov.b64 {z6,z7}, f3;\n"
        "\tmov.b64 {w0,w1}, g0;\n"
        "\tmov.b64 {w2,w3}, g1;\n"
        "\tmov.b64 {w4,w5}, g2;\n"
        "\tmov.b64 {w6,w7}, g3;\n"
        "\tadd.cc.u32  z1, z1, w0;\n"
        "\taddc.cc.u32 z2, z2, w1;\n"
        "\taddc.cc.u32 z3, z3, w2;\n"
        "\taddc.cc.u32 z4, z4, w3;\n"
        "\taddc.cc.u32 z5, z5, w4;\n"
        "\taddc.cc.u32 z6, z6, w5;\n"
        "\taddc.cc.u32 z7, z7, w6;\n"
        "\taddc.u32 z8, f8, w7;\n"
        "\t .reg .u64 sfz, sft; .reg .u32 sfc, sfq, sfl, sfh;\n"
        "mov.u32 sfq, z8;\n"
        "mov.b64 sfz, {z0, sfq};\n"
        "mul.wide.u32 sft, z8, 977;\n"
        "add.cc.u64 sft, sft, sfz;\n"
        "addc.u32 sfc, 0, 0;\n"
        "mov.b64 {sfl, sfh}, sft;\n"
        "mov.u32 z0, sfl;\n"
        "add.cc.u32 z1, z1, sfh;\n"
        "addc.cc.u32 z2, z2, sfc; \n"
        "\n"
        "\tmov.b64 %0, {z0,z1}; mov.b64 %1, {z2,z3}; mov.b64 %2, {z4,z5}; mov.b64 %3, {z6,z7};\n"
        "}\n"
        : "=l"(r0),"=l"(r1),"=l"(r2),"=l"(r3)
        : "l"(a[0]),"l"(a[1]),"l"(a[2]),"l"(a[3]),
          "l"(b[0]),"l"(b[1]),"l"(b[2]),"l"(b[3]));
    out[0]=r0;out[1]=r1;out[2]=r2;out[3]=r3;
}
