template<int BYTE> QWR_DEV int32_t qwr_by_signed_byte(uint32_t value){
    static_assert(BYTE>=0&&BYTE<4,"byte selector");
#ifdef __CUDA_ARCH__
    int32_t out;
    // Generic PRMT: select the byte once, replicate its sign into upper bytes.
    asm("prmt.b32 %0,%1,0,%2;" : "=r"(out) : "r"(value),"n"(((BYTE+8)*0x1110)|BYTE));
    return out;
#else
    const uint32_t byte=(value>>(BYTE*8))&255u;
    return (int32_t)(byte^128u)-128;
#endif
}

QWR_DEV int32_t qwr_divstep30_column(int32_t delta,uint32_t f,uint32_t g,
                                  uint32_t column,int32_t *top,int32_t *bottom){
    int32_t u=1-(int32_t)column,q=(int32_t)column;
    #pragma unroll
    for(int k=0;k<5;k++){
        const int32_t dc=delta<-6?-6:(delta>6?6:delta);
        const uint32_t fi=f*(2u-f*f),ratio=(g*fi)&63u;
        const uint64_t packed=QWR_BY_LUT[((uint32_t)(dc+6)<<6)|ratio];
        const uint32_t e=(uint32_t)packed,flags=(uint32_t)(packed>>32);
        const int32_t a=qwr_by_signed_byte<0>(e),b=qwr_by_signed_byte<1>(e);
        const int32_t c=qwr_by_signed_byte<2>(e),d=qwr_by_signed_byte<3>(e);
        const uint32_t nf=((uint32_t)a*f+(uint32_t)b*g)>>6;
        g=((uint32_t)c*f+(uint32_t)d*g)>>6;f=nf;
        const int32_t nu=a*u+b*q;
        q=c*u+d*q;u=nu;
        const int32_t sm=(int32_t)flags>>31;
        delta=((delta^sm)-sm)+qwr_by_signed_byte<0>(flags);
    }
    *top=u;*bottom=q;
    return delta;
}

QWR_DEV void qwr_condneg(uint32_t *X,uint32_t neg){
    const uint32_t msk=0u-neg; uint64_t c=neg;
    for(int i=0;i<9;i++){c+=(uint64_t)(X[i]^msk);X[i]=(uint32_t)c;c>>=32;}
}

QWR_DEV void qwr_canon(uint32_t *X){
    const uint32_t QWR_PL[9]=QWR_PL_INIT;
    const int32_t hi=(int32_t)X[8];
    int64_t acc=(int64_t)X[0]+(int64_t)hi*977;
    X[0]=(uint32_t)acc; acc>>=32;
    acc+=(int64_t)X[1]+(int64_t)hi;
    X[1]=(uint32_t)acc; acc>>=32;
    for(int i=2;i<8;i++){acc+=(int64_t)X[i];X[i]=(uint32_t)acc;acc>>=32;}
    X[8]=(uint32_t)acc;                               /* -1, 0 or 1 */
    const uint32_t mneg=(uint32_t)((int32_t)X[8]>>31);
    uint64_t c=0;
    for(int i=0;i<9;i++){c+=(uint64_t)X[i]+(uint64_t)(QWR_PL[i]&mneg);X[i]=(uint32_t)c;c>>=32;}
    uint32_t T[9]; c=1;
    for(int i=0;i<9;i++){c+=(uint64_t)X[i]+(uint64_t)(uint32_t)~QWR_PL[i];T[i]=(uint32_t)c;c>>=32;}
    const uint32_t keep=(uint32_t)((int32_t)T[8]>>31);
    for(int i=0;i<8;i++)X[i]=(X[i]&keep)|(T[i]&~keep);
}

__device__ __forceinline__ bool qwr_inverse_limbs_bounded(uint64_t *R,int lane){
    constexpr unsigned mask=0xffffffffu;
    const int digit=lane&7,row=lane>>3,start=lane&~7;
    const unsigned odd=row&1,rs=row>>1;
    const uint64_t rw=digit<2?R[0]:digit<4?R[1]:digit<6?R[2]:R[3];
    const uint32_t xl=(uint32_t)(rw>>(32*(digit&1)));
#if QSB_ISO_XR
    const uint64_t sw=pin_iso_invu_words[digit>>1];
    const uint32_t scaled=(uint32_t)(sw>>(32*(digit&1)));
#else
    const uint32_t scaled=(uint32_t)(digit==0);
#endif
    const uint32_t pl=digit==0?0xfffffc2fu:digit==1?0xfffffffeu:0xffffffffu;
    uint32_t x=odd?(rs?scaled:xl):(rs?0u:pl);
    int32_t xt=0,delta=1;
    unsigned batches=0;
    while(true){
        if(batches==QWR_ROOT_MAX_BATCHES)return false;
        ++batches;
        const uint32_t f0=__shfl_sync(mask,x,0),g0=__shfl_sync(mask,x,8);
        int32_t top,bottom;
        delta=qwr_divstep30_column(delta,f0,g0,rs,&top,&bottom);
        const int32_t selected=odd?bottom:top;
        const int32_t a=__shfl_sync(mask,selected,odd?24:0);
        const int32_t b=__shfl_sync(mask,selected,odd?8:16);
        const uint32_t y=__shfl_sync(mask,x,lane^8);
        const int32_t yt=__shfl_sync(mask,xt,lane^8);
        int64_t acc=(int64_t)a*(int64_t)x+(int64_t)b*(int64_t)y;
        uint32_t m=__shfl_sync(mask,(uint32_t)acc,start);
        m=(m*QWR_MM32)&QWR_MASK30&(0u-rs);
#if QWR_INVERSE_CORRECTION
        // The sparse modulus correction is one unsigned 32x32 product.
        // All eight lanes follow the same instruction stream.
        const uint32_t factor=digit==0?977u:digit==1?1u:0u;
        acc-=(int64_t)((uint64_t)factor*m);
#else
        if(digit==0)acc-=(int64_t)977*m;
        if(digit==1)acc-=(int64_t)m;
#endif
        int64_t high=(int64_t)a*xt+(int64_t)b*yt+(int64_t)m;
#if QWR_INVERSE_BIAS
        /* Add K*B to limbs 0..7, subtract K from limbs 1..8. The
         * telescoping bias is zero, and each low-limb accumulator is unsigned.
         * K=2^31 exceeds the absolute signed carry bound of the divstep rows. */
        const uint64_t biased=(uint64_t)acc+0x8000000000000000ULL-
                              (digit?0x80000000ULL:0ULL);
        const uint32_t lo=(uint32_t)biased,hi=(uint32_t)(biased>>32);
        const uint32_t prev0=__shfl_up_sync(mask,hi,1,8);
        const uint32_t prev=digit?prev0:0u;
        const uint32_t sum=lo+prev;
        const unsigned gen=(__ballot_sync(mask,sum<lo)>>start)&255u;
        const unsigned prop=(__ballot_sync(mask,sum==0xffffffffu)>>start)&255u;
        const unsigned carry=((prop+(gen<<1))^prop);
        const uint32_t low=sum+((carry>>digit)&1u);
        high+=(int64_t)__shfl_sync(mask,hi,start+7)-0x80000000LL;
        high+=(int64_t)((carry>>8)&1u);
#else
        const uint32_t lo=(uint32_t)acc;
        const int32_t hi=(int32_t)(acc>>32);
        const int32_t prev0=__shfl_up_sync(mask,hi,1,8);
        const int32_t prev=digit?prev0:0;
        const uint32_t positive=prev>0?(uint32_t)prev:0u;
        const uint32_t negative=prev<0?0u-(uint32_t)prev:0u;
        const uint32_t plus=lo+positive;
        const unsigned pg=(__ballot_sync(mask,plus<lo)>>start)&255u;
        const unsigned pp=(__ballot_sync(mask,plus==0xffffffffu)>>start)&255u;
        const unsigned carry=((pp+(pg<<1))^pp);
        const uint32_t sum=plus+((carry>>digit)&1u);
        const uint32_t minus=sum-negative;
        const unsigned bg=(__ballot_sync(mask,sum<negative)>>start)&255u;
        const unsigned bp=(__ballot_sync(mask,minus==0u)>>start)&255u;
        const unsigned borrow=((bp+(bg<<1))^bp);
        const uint32_t low=minus-((borrow>>digit)&1u);
        high+=(int64_t)__shfl_sync(mask,hi,start+7);
        high+=(int64_t)((carry>>8)&1u)-(int64_t)((borrow>>8)&1u);
#endif
        const uint32_t next0=__shfl_down_sync(mask,low,1,8);
        const uint32_t next=digit==7?(uint32_t)high:next0;
        x=(low>>30)|(next<<2);
        xt=(int32_t)(high>>30);
        if((__ballot_sync(mask,x!=0 || xt!=0)&0x0000ff00u)==0)break;
    }
    uint32_t out[9];
    #pragma unroll
    for(int i=0;i<8;i++)out[i]=__shfl_sync(mask,x,16+i);
    out[8]=(uint32_t)__shfl_sync(mask,xt,16);
    const uint32_t neg=(uint32_t)(__shfl_sync(mask,xt,0)<0);
    qwr_condneg(out,neg);
    qwr_canon(out);
    #pragma unroll
    for(int i=0;i<4;i++)R[i]=(uint64_t)out[2*i]|((uint64_t)out[2*i+1]<<32);
    R[4]=0;
    return true;
}
// The bounded path leaves R untouched on failure. Exponent p-2 is independent
// of the divstep table and all products use the carry-complete field helper.
// Canonicalize every product here; this exceptional path is not throughput work.
__device__ __noinline__ void qwr_fermat_scaled(uint64_t *R) {
    const uint64_t exponent[4]={0xFFFFFFFEFFFFFC2DULL,
        0xFFFFFFFFFFFFFFFFULL,0xFFFFFFFFFFFFFFFFULL,0xFFFFFFFFFFFFFFFFULL};
    uint64_t x[5]={R[0],R[1],R[2],R[3],0};
    uint64_t y[5]={1,0,0,0,0},tmp[5];
    for(int bit=255;bit>=0;--bit){
        qsb_field_mul(tmp,y,y); qsb_field_normalize(tmp);
        for(int k=0;k<5;++k)y[k]=tmp[k];
        if((exponent[bit>>6]>>(bit&63))&1ULL){
            qsb_field_mul(tmp,y,x); qsb_field_normalize(tmp);
            for(int k=0;k<5;++k)y[k]=tmp[k];
        }
    }
#if QSB_ISO_XR
    uint64_t scale[5]={pin_iso_invu_words[0],pin_iso_invu_words[1],
        pin_iso_invu_words[2],pin_iso_invu_words[3],0};
    qsb_field_mul(tmp,y,scale); qsb_field_normalize(tmp);
    for(int k=0;k<5;++k)y[k]=tmp[k];
#endif
    for(int k=0;k<5;++k)R[k]=y[k];
}
// All 32 lanes of warp zero pass the SAME canonical input; same scaled output.
QWR_DEV void qwr_inverse_scaled(uint64_t *R,int lane){
    if(qwr_inverse_limbs_bounded(R,lane))return;
    if(lane==0)qwr_fermat_scaled(R);
    for(int k=0;k<4;++k)R[k]=__shfl_sync(0xffffffffu,R[k],0);
    R[4]=0;
}
