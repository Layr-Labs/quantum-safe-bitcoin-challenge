template<int BYTE> QWR_DEV int32_t qwr_by_signed_byte(uint32_t value){
    static_assert(BYTE>=0&&BYTE<4,"byte selector");
#ifdef __CUDA_ARCH__
    int32_t out;
    /* Generic PRMT: select the byte once, replicate its sign into upper bytes. */
    asm("prmt.b32 %0,%1,0,%2;" : "=r"(out) : "r"(value),"n"(((BYTE+8)*0x1110)|BYTE));
    return out;
#else
    const uint32_t byte=(value>>(BYTE*8))&255u;
    return (int32_t)(byte^128u)-128;
#endif
}

template<int START> QWR_DEV int32_t qwr_by_signed10(uint32_t value){
    static_assert(START==0||START==10||START==20,"signed10 field selector");
#ifdef __CUDA_ARCH__
    int32_t out;
    asm("bfe.s32 %0,%1,%2,10;" : "=r"(out) : "r"(value),"n"(START));
    return out;
#else
    const uint32_t field=(value>>START)&1023u;
    return (int32_t)(field^512u)-512;
#endif
}

