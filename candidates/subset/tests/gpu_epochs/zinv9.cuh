template<int SHIFT,int WIDTH> ZI_DEV int32_t qsb_by9_signed(uint32_t p){
    const uint32_t mask=(1u<<WIDTH)-1u, sign=1u<<(WIDTH-1);
    return (int32_t)(((p>>SHIFT)&mask)^sign)-(int32_t)sign;
}
ZI_DEV int32_t qsb_divstep30_by9(int32_t delta,uint32_t f,uint32_t g,
        int32_t *ra,int32_t *rb,int32_t *rc,int32_t *rd){
    if(!(delta&1))return zi_divstep30_by(delta,f,g,ra,rb,rc,rd);
    int32_t u=1,v=0,q=0,r=1;
    #pragma unroll
    for(int group=0;group<3;group++){
        const uint32_t odd=g&1u;
        const bool swap=delta>0 && odd;
        if(swap){
            const uint32_t nf=g;
            g=(g-f)>>1;f=nf;delta=1-delta;
        }else{
            g=(g+(odd?f:0u))>>1;delta=1+delta;
        }
        // All products here deliberately use uint32 wrap; only low9 bits index.
        const uint32_t x=f*f-1u,gf=g*f;
        const uint32_t ratio=(gf*(1u-x+x*x))&511u;
        const int32_t dc=delta<-8?-8:(delta>8?8:delta);
        const uint32_t packed=QSB_BY9_ODD_LUT[((uint32_t)(dc+8)>>1)*512u+ratio];
        int32_t b=qsb_by9_signed<0,11>(packed),d=qsb_by9_signed<11,10>(packed);
        int32_t a=(int32_t)((0u-(uint32_t)b*ratio)&511u)
                    +512*qsb_by9_signed<21,2>(packed);
        int32_t c=(int32_t)((0u-(uint32_t)d*ratio)&511u)
                    -512*(int32_t)((packed>>23)&1u);
        const uint32_t nf=((uint32_t)a*f+(uint32_t)b*g)>>9;
        g=((uint32_t)c*f+(uint32_t)d*g)>>9;f=nf;
        const int32_t sm=-(int32_t)(packed>>29);
        delta=((delta^sm)-sm)+qsb_by9_signed<24,5>(packed);
        // M9 times the first-step matrix. Multiplication by2 is bounded and
        // signed products in the cumulative matrix stay within the30-bit bound.
        if(swap){
            const int32_t nb=2*a+b,nd=2*c+d;
            a=-b;c=-d;b=nb;d=nd;
        }else{
            a=2*a+(odd?b:0);c=2*c+(odd?d:0);
        }
        const int32_t nu=a*u+b*q,nv=a*v+b*r;
        q=c*u+d*q;r=c*v+d*r;u=nu;v=nv;
    }
    *ra=u;*rb=v;*rc=q;*rd=r;
    return delta;
}
